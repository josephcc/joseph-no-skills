import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

/**
 * One directory per page origin under <stateDir>/workspaces/<slug>/. It is the session
 * cwd for embedded-chat agents (D-16, F2-6): a scratch area with the page's instructions
 * mirrored as CLAUDE.md/AGENTS.md (for agents that read them; Claude gets the prompt
 * directly, D-27) and a .claude/settings.json that starts embedded chats in Claude Code's
 * auto permission mode with bypass disabled (threads-and-auto-mode plan, D-37; written once).
 */
export class Workspaces {
  readonly #stateDir: string;
  constructor(stateDir: string) { this.#stateDir = stateDir; }

  ensure(page: { slug: string; origin: string; title: string; instructions?: string }): string {
    const dir = join(this.#stateDir, 'workspaces', page.slug);
    mkdirSync(join(dir, '.claude'), { recursive: true });
    const settings = join(dir, '.claude', 'settings.json');
    if (!existsSync(settings)) {
      writeFileSync(settings, JSON.stringify({
        permissions: { defaultMode: 'auto', disableBypassPermissionsMode: 'disable' },
      }, null, 2) + '\n');
    }
    this.writeInstructions(dir, page);
    return dir;
  }

  writeInstructions(dir: string, page: { origin: string; title: string; instructions?: string }): void {
    const text = page.instructions?.trim()
      ? page.instructions
      : `# ${page.title}\n\nThis workspace belongs to the web page at ${page.origin}. The page's tools are available through the "page" MCP server. The page provided no further instructions.\n`;
    const body = `<!-- generated by webmcp-bridge from the page at ${page.origin}; edits are overwritten when the page reconnects -->\n\n${text}\n`;
    writeFileSync(join(dir, 'CLAUDE.md'), body);
    writeFileSync(join(dir, 'AGENTS.md'), body);
  }
}
